import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { spawn } from 'node:child_process';
import http from 'node:http';
const root=path.resolve('tests/.tmp');await fs.mkdir(root,{recursive:true});
test('HTTP persistence, origin boundaries, conflict protection, backups and static allowlist',async t=>{
  const data=await fs.mkdtemp(path.join(root,'server-'));
  const state={schema:1,revision:1,importedAt:new Date().toISOString(),projects:[{id:'a',name:'Test',status:'building',milestones:[]}],tasks:[{id:'t',project:'a',title:'Persist me',status:'todo'}],profile:{name:'Tester'},paths:{},alerts:{},notes:{},settings:{scanMinutes:10,scanDepth:2,staleDays:14},history:[]};
  await fs.writeFile(path.join(data,'state.json'),JSON.stringify(state));
  const child=spawn(process.execPath,['server.mjs'],{env:{...process.env,DAYBOOK_DATA_DIR:data,DAYBOOK_PORT:'18140'},windowsHide:true,stdio:['ignore','pipe','pipe']});
  t.after(async()=>{child.kill();await new Promise(r=>child.exitCode!==null?r():child.once('exit',r));if(!data.startsWith(root+path.sep))throw new Error('Unsafe cleanup');await fs.rm(data,{recursive:true,force:true});});
  await new Promise((resolve,reject)=>{const timer=setTimeout(()=>reject(new Error('Test server did not start')),10000);child.stdout.once('data',()=>{clearTimeout(timer);resolve();});child.once('exit',code=>{clearTimeout(timer);reject(new Error('Exited '+code));});});
  const url='http://127.0.0.1:18140';
  const post=(route,payload,extra={})=>fetch(url+route,{method:'POST',headers:{'Content-Type':'application/json','X-Daybook':'1',...extra},body:JSON.stringify(payload)});
  assert.equal((await fetch(url+'/data/state.json')).status,404);
  assert.equal((await fetch(url+'/.git/config')).status,404);
  assert.equal((await fetch(url+'/api/state',{headers:{Origin:'https://other.test'}})).status,403);
  const hostStatus=await new Promise(resolve=>http.get(url+'/api/state',{headers:{Host:'attacker.test:18140'}},res=>{res.resume();resolve(res.statusCode);}));assert.equal(hostStatus,403);
  assert.equal((await post('/api/action',{},{'X-Daybook':'wrong'})).status,403);
  assert.equal((await post('/api/action',{revision:1,action:{type:'project-update',id:'a',patch:{folderPath:path.resolve('.')}}})).status,422);
  const payload={revision:1,action:{type:'task-update',id:'t',patch:{status:'done'}}};
  assert.equal((await post('/api/action',payload)).status,200);
  assert.equal(JSON.parse(await fs.readFile(path.join(data,'state.json'),'utf8')).tasks[0].status,'done');
  assert.equal((await post('/api/action',payload)).status,409);
  assert.equal((await fs.readdir(path.join(data,'backups'))).length,1);
  assert.equal((await post('/api/action',{revision:2,action:{type:'task-update',id:'t',patch:{status:'banana'}}})).status,422);
  assert.equal((await post('/api/action',{revision:2,action:{type:'note',text:'x'.repeat(70000)}})).status,413);
  assert.equal((await fetch(url+'/api/handover')).status,200);
  assert.match((await fetch(url)).headers.get('content-security-policy'),/frame-ancestors 'none'/);
});
